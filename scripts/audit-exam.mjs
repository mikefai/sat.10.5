import assert from 'node:assert/strict'
import { allExamQuestions, numericResponse } from '../src/examQuestions.js'

const key = Object.fromEntries(allExamQuestions.map(q => [q.id, q.answer]))
const near = (id, expected) => assert.ok(Math.abs(numericResponse(key[id]) - expected) < 1e-9, `${id}: expected ${expected}, got ${key[id]}`)
const exact = (id, expected) => assert.equal(key[id], expected, id)

// Independently recompute the numerical keys most vulnerable to arithmetic,
// domain, rounding, or excluded-value mistakes.
near('M1Q01', (27 + 15) / 6)
exact('M1Q02', `${(100 - 80) / 80 * 100}%`)
near('M1Q03', (-2)**2 - 3*(-2) + 2)
near('M1Q04', 2*5)
near('M1Q05', (-5 - 7)/(4 - (-2)))
near('M1Q06', (2*3 + 4*5 + 6*2)/10)
near('M1Q08', 27*(5/3)**2)
exact('M1Q09', 'Zero')
exact('M1Q10', `$${164 + (239-164)/(65-40)*(100-40)}`)
near('M1Q11', (8**2/4)-1)
near('M1Q12', 66/(36+66))
near('M1Q13', (926-9*84)/(14-9))
near('M1Q14', (24/(-2*4))*(3-2)*(3+4))
exact('M1Q15', `${(8/2)**2+(6/2)**2}π`)
near('M1Q16', -6/2)
near('M1Q17', 6-5)
near('M1Q19', Math.log(108/4)/Math.log(3)/2)
near('M1Q20', Math.floor((75-18)/4))
near('M1Q21', 2)
near('M1Q22', 6/2)
near('M2Q01', -3*2+8)
near('M2Q02', Math.log2(32))
near('M2Q03', 9/Math.hypot(9,12))
near('M2Q05', 4**2-5)
exact('M2Q06', 'x − 4')
near('M2Q07', (72/360)*10**2)
near('M2Q08', 1-(-2/3)*6)
near('M2Q09', 6)
near('M2Q10', Math.round(800*(600/800)**4))
near('M2Q11', Math.log2(80/5)-1)
near('M2Q12', 4+2)
near('M2Q13', 3**2*2)
exact('M2Q14', '(0, 9)')
near('M2Q15', (300-84)/((18-6)+6))
exact('M2Q16', 'It is the line y = 3 with holes at x = −2 and x = 2')
near('M2Q17', 1)
near('M2Q18', (6**2/4)+7)
near('M2Q19', 6**2+4**2-4**2)
near('M2Q20', (18/Math.cbrt(486/18))/Math.cbrt(486/18)**2)
near('M2Q21', 4/5)
near('M2Q22', (240-48-60)*2/3+60)

// Verify restriction and tangency in the original equations, not just the key.
assert.notEqual(numericResponse(key.M1Q21), 4)
assert.equal((2**2-16)/(2-4), 2**2-5*2+12)
assert.equal(8**2-4*(Number(key.M1Q11)+1), 0)
assert.equal(6**2-4*(Number(key.M2Q18)-7), 0)
console.log('Independent exam arithmetic audit passed for 41 numerical and symbolic keys, including tangency and domain restrictions.')
